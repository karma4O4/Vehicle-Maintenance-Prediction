# Helper utilities
# ---------------------------------------------------------------------------

# Average annual mileage heuristics (miles/year) by vehicle type
_ANNUAL_MILEAGE_ESTIMATES = {
    "sedan": 12_000,
    "suv": 12_000,
    "coupe": 10_000,
    "truck": 25_000,
    "van": 20_000,
    "bus": 30_000,
}


def _classify_risk(score: float) -> str:
    """Map a 0-1 risk score to a human-readable risk level."""
    if score >= 0.86:
        return "CRITICAL"
    elif score >= 0.66:
        return "HIGH"
    elif score >= 0.36:
        return "MODERATE"
    else:
        return "LOW"


def _estimate_mileage(vehicle_model: str, vehicle_age: float) -> tuple[float, bool]:
    """
    Estimate mileage from vehicle age when mileage data is missing.

    Returns:
        (estimated_mileage, was_estimated)
    """
    model_key = str(vehicle_model).strip().lower()
    annual_miles = _ANNUAL_MILEAGE_ESTIMATES.get(model_key, 15_000)  # default fallback
    estimated = annual_miles * max(vehicle_age, 1)
    return estimated, True


def _build_human_prompt(ml_data: dict, rag_context: str) -> str:
    """
    Construct the human prompt from ML pipeline data and RAG context.
    Handles missing/noisy fields gracefully.
    """
    vehicle_model = ml_data.get("Vehicle_Model", "Unknown")
    vehicle_age = ml_data.get("Vehicle_Age", 0)
    mileage = ml_data.get("Mileage")
    risk_score = ml_data.get("Risk_Score", ml_data.get("risk_score", 0.5))
    reported_issues = ml_data.get("Reported_Issues", "N/A")
    fuel_type = ml_data.get("Fuel_Type", "N/A")
    odometer = ml_data.get("Odometer_Reading", "N/A")
    maintenance_history = ml_data.get("Maintenance_History", "Unknown")

    # Feature importance — accept list or string
    feat_importance = ml_data.get("Feature_Importance", ml_data.get("importance_factors", []))
    if isinstance(feat_importance, list):
        feat_importance_str = ", ".join(str(f) for f in feat_importance[:5]) or "N/A"
    else:
        feat_importance_str = str(feat_importance)

    # Handle missing mileage → estimate from Vehicle_Age
    mileage_display = mileage
    if mileage is None or mileage == 0 or str(mileage).strip() == "":
        estimated, _ = _estimate_mileage(vehicle_model, vehicle_age)
        mileage_display = f"~{int(estimated):,} (estimated from {vehicle_age}-year age; actual mileage unavailable)"
    else:
        mileage_display = f"{int(mileage):,}"

    risk_level = _classify_risk(float(risk_score))

    return HUMAN_PROMPT_TEMPLATE.format(
        vehicle_model=vehicle_model,
        mileage=mileage_display,
        vehicle_age=vehicle_age,
        maintenance_history=maintenance_history,
        reported_issues=reported_issues,
        fuel_type=fuel_type,
        odometer_reading=odometer,
        risk_score=f"{float(risk_score):.2f}",
        risk_level=risk_level,
        feature_importance=feat_importance_str,
        rag_context=rag_context if rag_context else "No additional context retrieved.",
    )


def _build_fallback_report(ml_data: dict, rag_context: str) -> str:
    """
    Generate a deterministic report when no LLM API key is available.
    Uses the REPORT_TEMPLATE with rule-based reasoning.
    """
    vehicle_model = ml_data.get("Vehicle_Model", "Unknown")
    vehicle_age = ml_data.get("Vehicle_Age", 0)
    mileage = ml_data.get("Mileage")
    risk_score = float(ml_data.get("Risk_Score", ml_data.get("risk_score", 0.5)))
    maintenance_history = ml_data.get("Maintenance_History", "Unknown")
    reported_issues = ml_data.get("Reported_Issues", 0)
    fuel_type = ml_data.get("Fuel_Type", "N/A")

    feat_importance = ml_data.get("Feature_Importance", ml_data.get("importance_factors", []))
    if isinstance(feat_importance, list):
        top_factors = feat_importance[:3]
    else:
        top_factors = [str(feat_importance)]

    risk_level = _classify_risk(risk_score)

    # Handle missing mileage
    mileage_note = ""
    if mileage is None or mileage == 0:
        estimated, _ = _estimate_mileage(vehicle_model, vehicle_age)
        mileage = estimated
        mileage_note = f" *(Mileage estimated at ~{int(mileage):,} miles from vehicle age of {vehicle_age} years; actual data unavailable.)*"

    # --- Build summary ---
    summary = (
        f"**{vehicle_model}** — {vehicle_age} year(s) old | "
        f"{int(mileage):,} miles | Fuel: {fuel_type}\n\n"
        f"Overall Risk: **{risk_level}** (Score: {risk_score:.2f}/1.00)\n\n"
        f"Maintenance History: **{maintenance_history}** | "
        f"Reported Issues: **{reported_issues}**{mileage_note}"
    )

    # --- Build risk analysis ---
    factor_bullets = "\n".join(f"  - **{f}**" for f in top_factors) if top_factors else "  - General Wear"
    risk_analysis = (
        f"The ML model assigned a **{risk_level}** risk score of **{risk_score:.2f}**. "
        f"The top contributing features are:\n{factor_bullets}\n\n"
    )
    if maintenance_history in ("Poor", "poor"):
        risk_analysis += "The vehicle's **poor maintenance history** significantly elevates the risk profile. "
    if vehicle_age >= 8:
        risk_analysis += f"At **{vehicle_age} years**, age-related degradation (seals, belts, fluid quality) is a major factor. "
    if rag_context:
        risk_analysis += f"\n\n**Supporting context:** {rag_context}"

    # --- Build recommended actions ---
    if risk_level == "CRITICAL":
        actions = (
            "1. **Immediate (0-48 hours):** Ground the vehicle and perform full brake, engine, and fluid inspection.\n"
            "2. **Short-term (1-2 weeks):** Replace all worn components identified in inspection; flush fluids.\n"
            "3. **Scheduled (next service cycle):** Transition to monthly inspection cadence and consider replacement evaluation."
        )
    elif risk_level == "HIGH":
        actions = (
            "1. **Immediate (0-48 hours):** Inspect brakes, tire tread, and oil quality.\n"
            "2. **Short-term (1-2 weeks):** Schedule a full diagnostic and address flagged components.\n"
            "3. **Scheduled (next service cycle):** Increase service frequency to bi-monthly."
        )
    elif risk_level == "MODERATE":
        actions = (
            "1. **Immediate (0-48 hours):** Visual inspection of tires and fluid levels.\n"
            "2. **Short-term (1-2 weeks):** Schedule routine service appointment.\n"
            "3. **Scheduled (next service cycle):** Continue normal maintenance cadence with attention to flagged areas."
        )
    else:
        actions = (
            "1. **Immediate (0-48 hours):** No urgent action required.\n"
            "2. **Short-term (1-2 weeks):** Monitor for any unusual sounds or dashboard warnings.\n"
            "3. **Scheduled (next service cycle):** Maintain regular service schedule."
        )

    return REPORT_TEMPLATE.format(
        summary=summary,
        risk_analysis=risk_analysis,
        actions=actions,
    )


